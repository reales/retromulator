inline constexpr double LN2_64_HI = 0.01083042468962958;
inline constexpr double LN2_64_LO = 6.619564634077006e-12;
inline constexpr double INV_LN2_64 = 92.33248261689366;

inline double exp (double x)
{
    if (std::isnan (x) || std::fabs (x) >= 700.0)
        return std::exp (x);
    constexpr double SHIFT = 6755399441055744.0;
    const double kb = x * INV_LN2_64 + SHIFT;
    const double kf = kb - SHIFT;
    const int64_t k = (int64_t) (int32_t) (uint32_t) std::bit_cast<uint64_t> (kb);
    const double r = (x - kf * LN2_64_HI) - kf * LN2_64_LO;
    const double r2 = r * r;
    const double p = r + r2 * (0.5 + r * (1.0 / 6.0)) + r2 * r2 * (1.0 / 24.0 + r * (1.0 / 120.0));
    const double t = EXP2_64[(size_t) (k & 63)];
    const double y = t + t * p;
    return std::bit_cast<double> (std::bit_cast<uint64_t> (y) + ((uint64_t) (k >> 6) << 52));
}

inline double tanh (double x)
{
    const double a = std::fabs (x);
    double t;
    if (a < 0.02)
    {
        const double a2 = a * a;
        t = a * (1.0 - a2 * (1.0 / 3.0 - a2 * (2.0 / 15.0 - a2 * (17.0 / 315.0))));
    }
    else if (a > 20.0)
        t = 1.0;
    else
        t = 1.0 - 2.0 / (exp (2.0 * a) + 1.0);
    return std::copysign (t, x);
}
